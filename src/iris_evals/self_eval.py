"""
self_eval.py — run_self_eval() and helpers for in-process agent self-evaluation.

The agent calls run_self_eval() on startup (or on a schedule) without any
external files or config — everything is resolved from:
  1. The agent's own /.well-known/agent-card.json (read from disk)
  2. The iris-evals built-in registry (datasets, rubrics, thresholds)

Usage in app.py:
    from iris_evals import run_self_eval

    @app.on_event("startup")
    async def startup():
        report = await run_self_eval(agent_url="http://localhost:8080")
        if not report.passed:
            logger.warning(f"[IRIS EVALS] Self-eval FAILED — {report.summary}")

Background loop usage:
    from iris_evals import self_eval_loop
    asyncio.create_task(self_eval_loop(agent_url="http://localhost:8080", interval_seconds=300))
"""

from __future__ import annotations

import asyncio
import json
import logging
from pathlib import Path
from typing import Callable

from iris_evals.registry import get_dataset, get_rubric, get_thresholds
from iris_evals.runner import EvalSuite
from iris_evals.schemas import EvalConfig, EvalReport, EvalType, GoldenRecord

logger = logging.getLogger("iris_evals.self_eval")

# Default locations where the agent card may live (checked in order)
_CARD_SEARCH_PATHS = [
    Path(".well-known/agent-card.json"),
    Path("agent-card.json"),
    Path("src/.well-known/agent-card.json"),
]


# ── Agent card loading ─────────────────────────────────────────────────────────

def _load_agent_card(card_path: str | Path | None = None) -> dict:
    """Load agent card from disk. Tries default paths if card_path is None."""
    if card_path:
        paths = [Path(card_path)]
    else:
        paths = _CARD_SEARCH_PATHS

    for p in paths:
        if p.exists():
            return json.loads(p.read_text(encoding="utf-8"))

    raise FileNotFoundError(
        "agent-card.json not found. Searched: "
        + ", ".join(str(p) for p in paths)
        + ". Pass card_path= explicitly or place agent-card.json in .well-known/."
    )


def _parse_x_evals(card: dict, agent_url: str) -> EvalConfig:
    """
    Build EvalConfig from the agent card's x_evals block + registry.

    x_evals shape (auto-generated by iris-sap-agent-skill):
    {
      "evaluators": ["deterministic", "safety"],
      "dataset": "builtin",                        # or a file path
      "threshold_profile": "deterministic_strict"  # optional
    }
    """
    agent_name = card.get("name", "unknown-agent")
    x_evals    = card.get("x_evals", {})

    # -- Evaluators
    raw_types  = x_evals.get("evaluators", ["deterministic"])
    eval_types = [EvalType(t) for t in raw_types]

    # -- Golden dataset: builtin (registry) OR file path OR builtin+file merge
    dataset_spec = x_evals.get("dataset", "builtin")
    if dataset_spec == "builtin":
        records = get_dataset(agent_name)
    elif dataset_spec.startswith("builtin+"):
        # merge built-in records with custom file
        extra_path = dataset_spec[len("builtin+"):]
        extra_data = json.loads(Path(extra_path).read_text(encoding="utf-8"))
        records    = get_dataset(agent_name) + [GoldenRecord(**r) for r in extra_data]
    else:
        # pure file path
        data    = json.loads(Path(dataset_spec).read_text(encoding="utf-8"))
        records = [GoldenRecord(**r) for r in data]

    # -- Rubric for LLM_AS_JUDGE
    rubric = get_rubric(agent_name) if EvalType.LLM_AS_JUDGE in eval_types else None

    # -- Thresholds
    thresholds = get_thresholds(agent_name)
    # Allow x_evals to override individual thresholds
    thresholds.update(x_evals.get("thresholds", {}))

    # -- Safety records (tagged subset of golden dataset)
    safety_records = [r for r in records if "safety" in r.tags]

    return EvalConfig(
        agent_name    = agent_name,
        agent_url     = agent_url,
        evaluators    = eval_types,
        judge_rubric  = rubric,
        safety_cases  = safety_records,
        thresholds    = thresholds,
        use_a2a       = card.get("x_evals", {}).get("use_a2a", True),
        # Store records directly — runner will use them via golden_records field
        golden_records = records,
    )


# ── EvalReport summary property ────────────────────────────────────────────────

def _report_summary(report: EvalReport) -> str:
    parts = []
    for eval_type, m in report.metrics.items():
        if isinstance(m, dict) and "pass_rate" in m:
            pct = round(m["pass_rate"] * 100, 1)
            parts.append(f"{eval_type}={pct}%")
    return f"pass_rate={round(report.pass_rate * 100, 1)}% [{', '.join(parts)}]"


# ── Core public API ────────────────────────────────────────────────────────────

async def run_self_eval(
    agent_url: str = "http://localhost:8080",
    card_path: str | Path | None = None,
    on_fail: Callable[[EvalReport], None] | None = None,
) -> EvalReport:
    """
    Run the agent's own evals and return the report.

    Args:
        agent_url:  Where the agent is listening (default localhost:8080)
        card_path:  Path to agent-card.json (auto-discovered if None)
        on_fail:    Optional callback called with the report when evals fail

    Returns:
        EvalReport — check report.passed for pass/fail
    """
    card   = _load_agent_card(card_path)
    config = _parse_x_evals(card, agent_url)

    logger.info(
        "[IRIS EVALS] Running self-eval for '%s' — evaluators: %s",
        config.agent_name,
        [e.value for e in config.evaluators],
    )

    suite  = _SelfEvalSuite(config)
    report = await suite.arun()

    summary = _report_summary(report)
    if report.overall_passed:
        logger.info("[IRIS EVALS] PASS — %s", summary)
    else:
        logger.warning("[IRIS EVALS] FAIL — %s", summary)
        if on_fail:
            on_fail(report)

    return report


async def self_eval_loop(
    agent_url: str = "http://localhost:8080",
    card_path: str | Path | None = None,
    interval_seconds: int = 300,
    on_fail: Callable[[EvalReport], None] | None = None,
) -> None:
    """
    Run self-evals on a repeating background loop.

    Create as an asyncio task in your app startup:
        asyncio.create_task(self_eval_loop("http://localhost:8080"))

    Args:
        agent_url:        Where the agent listens
        card_path:        Path to agent-card.json (auto-discovered if None)
        interval_seconds: How often to re-run (default 5 minutes)
        on_fail:          Called with the report on every failure
    """
    logger.info(
        "[IRIS EVALS] Background eval loop started — interval=%ds", interval_seconds
    )
    while True:
        await asyncio.sleep(interval_seconds)
        try:
            await run_self_eval(agent_url=agent_url, card_path=card_path, on_fail=on_fail)
        except Exception as exc:
            logger.error("[IRIS EVALS] Self-eval loop error: %s", exc)


# ── SelfEvalSuite — runner that accepts pre-loaded records ────────────────────

class _SelfEvalSuite(EvalSuite):
    """EvalSuite subclass that uses pre-loaded records instead of reading a file."""

    async def arun(self) -> EvalReport:
        # Pull the pre-loaded records from the config field we injected
        config  = self.config
        records = config.golden_records or []

        import datetime, uuid
        from iris_evals import evaluators
        from iris_evals.runner import _aggregate
        from iris_evals.schemas import EvalReport as _Report

        all_results = []
        all_metrics = {}

        for eval_type in config.evaluators:

            if eval_type == EvalType.DETERMINISTIC:
                det_records = [r for r in records if "deterministic" in r.tags or not r.tags]
                if det_records:
                    res = await evaluators.deterministic.run(config, det_records)
                    all_results.extend(res)
                    all_metrics["deterministic"] = _aggregate(res)

            elif eval_type == EvalType.PROBABILISTIC:
                prob_records = [r for r in records if "probabilistic" in r.tags]
                if prob_records:
                    res, metrics = await evaluators.probabilistic.run(config, prob_records)
                    all_results.extend(res)
                    all_metrics["probabilistic"] = metrics

            elif eval_type == EvalType.LLM_AS_JUDGE:
                if config.judge_rubric:
                    res, metrics = await evaluators.llm_judge.run(config, records, config.judge_rubric)
                    all_results.extend(res)
                    all_metrics["llm_as_judge"] = metrics

            elif eval_type == EvalType.TRACE:
                res = await evaluators.trace.run(config, records)
                all_results.extend(res)
                all_metrics["trace"] = _aggregate(res)

            elif eval_type == EvalType.SAFETY:
                safety_records = config.safety_cases or [r for r in records if "safety" in r.tags]
                if safety_records:
                    res = await evaluators.safety.run(config, safety_records)
                    all_results.extend(res)
                    all_metrics["safety"] = _aggregate(res)

            elif eval_type == EvalType.PERFORMANCE:
                res, metrics = await evaluators.performance.run(config, records)
                all_results.extend(res)
                all_metrics["performance"] = metrics

        total  = len(all_results)
        passed = sum(1 for r in all_results if r.passed)

        # Check against thresholds
        overall_passed = _check_thresholds(all_metrics, config.thresholds)

        return _Report(
            agent_name     = config.agent_name,
            eval_types_run = list(config.evaluators),
            total_cases    = total,
            passed         = passed,
            failed         = total - passed,
            pass_rate      = round(passed / total, 4) if total else 0.0,
            results        = all_results,
            metrics        = all_metrics,
            run_id         = str(uuid.uuid4())[:8],
            timestamp      = datetime.datetime.utcnow().isoformat(timespec="seconds") + "Z",
        )


def _check_thresholds(metrics: dict, thresholds: dict[str, float]) -> bool:
    for eval_type, threshold in thresholds.items():
        m = metrics.get(eval_type, {})
        actual = m.get("pass_rate", m.get("accuracy", 1.0))
        if actual < threshold:
            return False
    return True
